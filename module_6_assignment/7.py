str="hello"
print(str)
#access the first character of a string using index value.
print(str[0])
# Write a Python program to access the string from the second position onwards using slicing.
print(str[1:])
#Write a Python program to access a string up to the fifth character.
print(str[:5])
#print the substring between index values 1 and 4
print(str[1:4])
#print a string from the last character
print(str[::-1])
#print every alternate character from the string starting from index 1
print(str[1::2])
